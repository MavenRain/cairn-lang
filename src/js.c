#define CALL_COUNT (sizeof CALLS / sizeof CALLS[0])

static int put(Js *o, const char *s) {
  o->ok = o->ok && fputs(s, o->out) >= 0;
  return o->ok;
}

static int put_u64(Js *o, uint64_t v) {
  o->ok = o->ok && fprintf(o->out, "%" PRIu64, v) >= 0;
  return o->ok;
}

static int put_lines(Js *o, const char *const *lines, size_t n) {
  size_t i;
  int ok = 1;
  for (i = 0; i < n && ok; i++) ok = put(o, lines[i]) && put(o, "\n");
  return ok;
}

/* A single-quoted JS string of S. */
static int put_quoted(Js *o, const char *s) {
  size_t i;
  int ok = put(o, "'");
  for (i = 0; s[i] != '\0' && ok; i++) {
    ok = (s[i] == '\'' || s[i] == '\\' ? put(o, "\\") : 1) && fputc(s[i], o->out) != EOF;
  }
  o->ok = ok;
  return ok && put(o, "'");
}

static int indent(Js *o, unsigned depth) {
  unsigned i;
  int ok = 1;
  for (i = 0; i < depth && ok; i++) ok = put(o, "  ");
  return ok;
}

static int no_code(Js *o, const char *what, unsigned v) {
  fprintf(o->err, "BUILD: the JS back end has no code for %s %u\n", what, v);
  o->said = 1;
  o->ok = 0;
  return 0;
}

static size_t call_slot(IrCall c) {
  size_t i = 0;
  while (i < CALL_COUNT && CALLS[i].call != c) i++;
  return i;
}

static const char *op_name(IrOp op) {
  switch (op) {
    case IR_OP_ADD: return "wAdd";
    case IR_OP_SUB: return "wSub";
    case IR_OP_MUL: return "wMul";
    case IR_OP_EQ: return "wEq";
    case IR_OP_LE: return "wLe";
    case IR_OP_ADD_CARRY: return "wAddCarry";
    case IR_OP_MUL_CARRY: return "wMulCarry";
    case IR_OP_OR: return "wOr";
    case IR_OP_LT: return "wLt";
    case IR_OP_DIV: return "wDiv";
    case IR_OP_MOD: return "wMod";
  }
  return NULL;
}

static const char *arg_name(IrScalar t) {
  switch (t) {
    case IR_SCALAR_NAT: return "natArg";
    case IR_SCALAR_FLAG: return "flagArg";
    case IR_SCALAR_U256: return "u256Arg";
  }
  return NULL;
}

/* The bit set of the IrCall kinds that E or B calls (wasm.c calls_expr). */
static unsigned calls_expr(const IrExpr *e) {
  size_t i;
  unsigned m = 0;
  switch (e->kind) {
    case IR_EXPR_CONST:
    case IR_EXPR_LOCAL:
      return 0;
    case IR_EXPR_BINARY:
      return calls_expr(e->left) | calls_expr(e->right);
    case IR_EXPR_LOAD:
      return calls_expr(e->left);
    case IR_EXPR_CALL:
      for (i = 0; i < e->arg_count; i++) m |= calls_expr(e->args[i]);
      return m | (1u << e->call);
  }
  return 0;
}

static unsigned calls_block(const IrBlock *b);

static unsigned calls_stmt(const IrStmt *st) {
  size_t k;
  unsigned m = 0;
  switch (st->kind) {
    case IR_STMT_SET:
    case IR_STMT_RETURN:
      return calls_expr(st->expr);
    case IR_STMT_ALLOC:
      for (k = 0; k < st->field_count; k++) m |= calls_expr(st->fields[k]);
      return m;
    case IR_STMT_IF:
      return calls_expr(st->expr) | calls_block(&st->body) | calls_block(&st->otherwise);
    case IR_STMT_SWITCH:
      for (k = 0; k < st->arm_count; k++) m |= calls_block(&st->arms[k]);
      return m | calls_expr(st->expr);
    case IR_STMT_REPEAT:
    case IR_STMT_WHILE:
      return calls_expr(st->expr) | calls_block(&st->body);
    case IR_STMT_TRAP:
      return 0;
  }
  return 0;
}

static unsigned calls_block(const IrBlock *b) {
  size_t i;
  unsigned m = 0;
  for (i = 0; i < b->count; i++) m |= calls_stmt(b->items[i]);
  return m;
}

static int emit_expr(Js *o, const IrExpr *e);

static int emit_list(Js *o, const IrExpr *const *items, size_t n) {
  size_t i;
  int ok = 1;
  for (i = 0; i < n && ok; i++) ok = (i == 0 || put(o, ", ")) && emit_expr(o, items[i]);
  return ok;
}

static int emit_expr(Js *o, const IrExpr *e) {
  const char *name;
  size_t slot;
  switch (e->kind) {
    case IR_EXPR_CONST:
      return put_u64(o, e->value) && put(o, "n");
    case IR_EXPR_LOCAL:
      return put(o, "l") && put_u64(o, e->local);
    case IR_EXPR_BINARY:
      name = op_name(e->op);
      return name == NULL ? no_code(o, "operator", (unsigned)e->op)
                          : (put(o, name) && put(o, "(") && emit_expr(o, e->left) && put(o, ", ") &&
                             emit_expr(o, e->right) && put(o, ")"));
    case IR_EXPR_LOAD:
      return put(o, "ld(") && emit_expr(o, e->left) && put(o, ", ") && put_u64(o, e->field) && put(o, ")");
    case IR_EXPR_CALL:
      slot = call_slot(e->call);
      return slot == CALL_COUNT ? no_code(o, "prelude call", (unsigned)e->call)
                                : (put(o, CALLS[slot].name) && put(o, "(") && emit_list(o, e->args, e->arg_count) &&
                                   put(o, ")"));
  }
  return no_code(o, "expression", (unsigned)e->kind);
}

static int emit_block(Js *o, const IrBlock *b, unsigned depth);

/* REPEAT: counter := expr, then the body counter times. WHILE: the same, but
   only while local != 0 too. The counter goes down by 1 after each run. */
static int emit_loop(Js *o, const IrStmt *st, int is_while, unsigned depth) {
  return indent(o, depth) && put(o, "l") && put_u64(o, st->counter) && put(o, " = ") && emit_expr(o, st->expr) &&
         put(o, ";\n") && indent(o, depth) && put(o, "while (l") && put_u64(o, st->counter) && put(o, " > 0n") &&
         (!is_while || (put(o, " && l") && put_u64(o, st->local) && put(o, " !== 0n"))) && put(o, ") {\n") &&
         emit_block(o, &st->body, depth + 1u) && indent(o, depth + 1u) && put(o, "l") && put_u64(o, st->counter) &&
         put(o, " -= 1n;\n") && indent(o, depth) && put(o, "}\n");
}

static int emit_stmt(Js *o, const IrStmt *st, unsigned depth) {
  size_t k;
  int ok;
  switch (st->kind) {
    case IR_STMT_SET:
      return indent(o, depth) && put(o, "l") && put_u64(o, st->local) && put(o, " = ") && emit_expr(o, st->expr) &&
             put(o, ";\n");
    case IR_STMT_ALLOC:
      return indent(o, depth) && put(o, "l") && put_u64(o, st->local) && put(o, " = alloc([") &&
             emit_list(o, st->fields, st->field_count) && put(o, "]);\n");
    case IR_STMT_IF:
      return indent(o, depth) && put(o, "if (") && emit_expr(o, st->expr) && put(o, " !== 0n) {\n") &&
             emit_block(o, &st->body, depth + 1u) && indent(o, depth) && put(o, "} else {\n") &&
             emit_block(o, &st->otherwise, depth + 1u) && indent(o, depth) && put(o, "}\n");
    case IR_STMT_SWITCH:
      ok = indent(o, depth) && put(o, "switch (") && emit_expr(o, st->expr) && put(o, ") {\n");
      for (k = 0; k < st->arm_count && ok; k++) {
        ok = indent(o, depth + 1u) && put(o, "case ") && put_u64(o, (uint64_t)k) && put(o, "n:\n") &&
             emit_block(o, &st->arms[k], depth + 2u) && indent(o, depth + 2u) && put(o, "break;\n");
      }
      return ok && indent(o, depth + 1u) && put(o, "default:\n") && indent(o, depth + 2u) && put(o, "trap();\n") &&
             indent(o, depth) && put(o, "}\n");
    case IR_STMT_REPEAT:
      return emit_loop(o, st, 0, depth);
    case IR_STMT_WHILE:
      return emit_loop(o, st, 1, depth);
    case IR_STMT_TRAP:
      return indent(o, depth) && put(o, "trap();\n");
    case IR_STMT_RETURN:
      return indent(o, depth) && put(o, o->result == IR_SCALAR_U256 ? "return big(" : "return ") &&
             emit_expr(o, st->expr) && put(o, o->result == IR_SCALAR_U256 ? ");\n" : ";\n");
  }
  return no_code(o, "statement", (unsigned)st->kind);
}

static int emit_block(Js *o, const IrBlock *b, unsigned depth) {
  size_t i;
  int ok = 1;
  for (i = 0; i < b->count && ok; i++) ok = emit_stmt(o, b->items[i], depth);
  return ok;
}

/* Entry INDEX as `function eINDEX(a0, ...)`: it resets the heap, checks and
   copies the arguments into the IR locals, then runs the body. */
static int emit_func(Js *o, const IrFunc *fn, size_t index) {
  size_t i;
  const char *conv;
  int ok;
  o->result = fn->result;
  ok = put(o, "\nfunction e") && put_u64(o, (uint64_t)index) && put(o, "(");
  for (i = 0; i < fn->param_count && ok; i++) ok = (i == 0 || put(o, ", ")) && put(o, "a") && put_u64(o, (uint64_t)i);
  ok = ok && put(o, ") {\n  reset();\n");
  for (i = 0; i < fn->local_count && ok; i++) {
    conv = i < fn->param_count ? arg_name(fn->params[i]) : "";
    ok = conv == NULL ? no_code(o, "scalar", (unsigned)fn->params[i])
                      : (put(o, "  let l") && put_u64(o, (uint64_t)i) &&
                         (i < fn->param_count ? put(o, " = ") && put(o, conv) && put(o, "(a") &&
                                                    put_u64(o, (uint64_t)i) && put(o, ");\n")
                                              : put(o, " = 0n;\n")));
  }
  return ok && emit_block(o, &fn->body, 1u) && put(o, "}\n");
}

int js_write(const IrProgram *prog, FILE *out, FILE *err) {
  Js o;
  unsigned used = 0;
  unsigned needs = 0;
  size_t i;
  int ok = 1;
  o.out = out;
  o.err = err;
  o.result = IR_SCALAR_NAT;
  o.said = 0;
  o.ok = 1;
  for (i = 0; i < prog->func_count; i++) used |= calls_block(&prog->funcs[i].body);
  for (i = 0; i < CALL_COUNT; i++) needs |= ((used >> CALLS[i].call) & 1u) ? CALLS[i].needs : 0u;
  for (i = 0; i < CALL_COUNT && ok; i++) ok = !((used >> CALLS[i].call) & 1u) || CALLS[i].def != NULL;
  if (!ok) {
    fprintf(err, "PLANNED: the JS prelude has no %s yet (S9 B2): use the Wasm build\n", CALLS[i - 1].name);
    return 0;
  }
  ok = put_lines(&o, RUNTIME, sizeof RUNTIME / sizeof RUNTIME[0]) &&
       (!(needs & NEED_SHA) || put_lines(&o, SHA_PART, sizeof SHA_PART / sizeof SHA_PART[0])) &&
       (!(needs & NEED_EC) || put_lines(&o, EC_PART, sizeof EC_PART / sizeof EC_PART[0]));
  for (i = 0; i < CALL_COUNT && ok; i++) {
    ok = !((used >> CALLS[i].call) & 1u) || (put(&o, CALLS[i].def) && put(&o, "\n"));
  }
  for (i = 0; i < prog->func_count && ok; i++) ok = emit_func(&o, &prog->funcs[i], i);
  ok = ok && put(&o, "\nexport {");
  for (i = 0; i < prog->func_count && ok; i++) {
    ok = put(&o, i == 0 ? " e" : ", e") && put_u64(&o, (uint64_t)i) && put(&o, " as ") &&
         put_quoted(&o, prog->funcs[i].name);
  }
  ok = ok && put(&o, " };\n");
  if (!ok && !o.said) fprintf(err, "IO: the JS module write failed\n");
  return ok;
}
