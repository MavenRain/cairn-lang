/* The WGSL back end (S10 B1, Q-S10-2 and Q-S10-3). It writes one WGSL module of
   compute shaders from the IR that src/wasm.c takes:
   `langc build PROG --wgsl OUT.wgsl`.
   Module layout:
   - The runtime. A word is a vec2<u32> (low, high) from 0 to 2^64 - 1, and
     each word op is exact on u64 as in ir.h: w_mul and w_mul_carry use 32-bit
     products from 16-bit partial products (w_mul32), w_div and w_mod divide
     by shift and subtract (w_divmod).
   - The heap. A WGSL function can take a pointer into the function or the
     private address space only, and the prelude allocates blocks, so the heap
     is one module-scope storage buffer `heap` (binding 2) that each entry
     uses. Invocation idx owns the HEAP_WORDS words from hb = idx *
     HEAP_WORDS, and an address is a word index in that slice. The words
     before HEAP_START read as 0, so address 0 is the null block as in wasm.c.
     An alloc past the slice sets the trap flag tr and gives 0 (the Wasm heap
     limit).
   - The prelude: the IrCall functions that the module calls, in IrCall order,
     on words. A U256 is a block of 4 words, low limb first; the prelude
     works on its 8 u32 limbs, low first (LIMB_PART, SHA_PART, EC_PART).
   - One compute entry for each IR entry, with its name, and its bindings
     NAME_in (binding 0, read) and NAME_out (binding 1, read_write), each an
     array<u32>. Invocation idx reads row idx of NAME_in (a Nat or Flag
     parameter is 2 u32, low first; a U256 is 8 u32, low first, copied to a
     new block) and writes row idx of NAME_out: a status u32 (0 ok, 1 TRAP),
     then the result u32s in the same layout. A Flag argument larger than 1
     traps, as in wasm.c. An idx past the rows of NAME_out returns.
   Traps: an op that traps in wasm.c sets tr, and the code goes on; each loop
   stops when tr is set, and the RETURN of the entry writes status 1 when tr
   is set. A TRAP statement, or a SWITCH value with no arm, writes status 1
   and returns. */
